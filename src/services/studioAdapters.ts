import type { PublisherElement, PublisherPage, PublisherProject } from "../types/publisher";
import { createWebProject, type WebBlock, type WebBlockType, type WebProject } from "../utils/webStudioEngine";
import type { StoredCreationProject } from "./creationProjectStore";

const now = () => Date.now();
const uid = (prefix: string) => `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;

function textElement(name: string, text: string, x: number, y: number, width: number, height: number, fontSize: number, weight: "400"|"500"|"600"|"700"|"800"|"900" = "700"): PublisherElement {
  return {
    id: uid("text"), name, type: "text", x, y, width, height, rotation: 0, zIndex: 2, opacity: 1,
    text, fontFamily: "Arial", fontSize, fontWeight: weight, italic: false, underline: false,
    textAlign: "left", textColor: "#172033", lineHeight: Math.round(fontSize * 1.2), letterSpacing: 0,
    fillColor: "transparent", borderColor: "transparent", borderWidth: 0, borderRadius: 0,
  };
}

export function creationToPublisherProject(source: StoredCreationProject): PublisherProject {
  const created = now();
  const pageId = uid("page");
  const generatedText = typeof source.generated?.text === "string" ? source.generated.text : source.content.body;
  const body = generatedText.slice(0, 1800);
  const elements: PublisherElement[] = [
    { id: uid("accent"), name: "AI Accent", type: "rectangle", x: 54, y: 54, width: 150, height: 12, rotation: 0, zIndex: 1, opacity: 1, fillColor: "#7C3AED", borderColor: "transparent", borderWidth: 0, borderRadius: 6 },
    textElement("AI Headline", source.content.headline || source.title, 54, 90, 700, 120, 42, "900"),
    textElement("AI Body", body || source.sourcePrompt, 54, 230, 700, 270, 18, "500"),
    textElement("AI CTA", source.content.sections.at(-1) || "Call to action", 54, 555, 500, 60, 20, "800"),
  ];
  const firstImage = source.assets?.find((asset) => asset.kind === "image" && asset.uri);
  if (firstImage?.uri) {
    elements.push({ id: uid("image"), name: "Generated image", type: "image", x: 790, y: 90, width: 320, height: 450, rotation: 0, zIndex: 1, opacity: 1, fillColor: "#E2E8F0", borderColor: "transparent", borderWidth: 0, borderRadius: 16, imageFit: "cover", imageUri: firstImage.uri } as PublisherElement);
  }
  const page: PublisherPage = { id: pageId, name: "AI Generated", width: 1200, height: 675, orientation: "landscape", sizeKey: "custom", backgroundColor: "#FFFFFF", margin: 36, bleed: 0, elements };
  return { id: uid("project"), name: source.title, createdAt: created, updatedAt: created, pages: [page], activePageId: pageId, autoSave: true, version: 2, description: `Generated by Yaposan Create from: ${source.sourcePrompt}`, tags: ["AI", "Yaposan Create", source.projectType] };
}

function sectionType(section: string, index: number): WebBlockType {
  const s = section.toLowerCase();
  if (index === 0 || /hero|opening/.test(s)) return "hero";
  if (/contact|form|reservation|signup/.test(s)) return "form";
  if (/gallery|portfolio|proof/.test(s)) return "gallery";
  if (/price|plan/.test(s)) return "pricing";
  if (/faq|question/.test(s)) return "faq";
  if (/image|visual/.test(s)) return "image";
  if (/call to action|cta/.test(s)) return "button";
  return "text";
}

export function creationToWebProject(source: StoredCreationProject): WebProject {
  const project = createWebProject(source.title);
  const generatedText = typeof source.generated?.text === "string" ? source.generated.text : source.content.body;
  const sections = source.content.sections.length ? source.content.sections : ["Hero", "About", "Offer", "Contact"];
  const blocks: WebBlock[] = sections.map((section, index) => ({
    id: `${sectionType(section,index)}-${index + 1}`,
    type: sectionType(section,index),
    title: index === 0 ? source.content.headline : section,
    content: index === 0 ? generatedText.slice(0, 700) : `${section} — ${source.sourcePrompt}`,
    visible: true,
  }));
  blocks.push({ id: "footer-ai", type: "footer", title: source.title, content: "Created with Yaposan", visible: true });
  return { ...project, blocks, seo: { title: source.title, description: generatedText.slice(0, 160), keywords: `${source.projectType}, ${source.title}, Yaposan` } };
}

export type PresentationDraft = { id: string; title: string; slides: Array<{ id: string; title: string; body: string }>; editable: true };
export function creationToPresentation(source: StoredCreationProject): PresentationDraft {
  const generatedText = typeof source.generated?.text === "string" ? source.generated.text : source.content.body;
  const sections = source.content.sections.length ? source.content.sections : ["Title", "Context", "Key points", "Recommendation", "Next steps"];
  return { id: source.id, title: source.title, editable: true, slides: sections.map((title, index) => ({ id: `slide-${index + 1}`, title: index === 0 ? source.title : title, body: index === 0 ? generatedText.slice(0, 500) : `${title}: ${source.sourcePrompt}` })) };
}

export function projectRouteWithCreation(source: StoredCreationProject) {
  const sep = source.route.includes("?") ? "&" : "?";
  return `${source.route}${sep}creationProject=${encodeURIComponent(source.id)}&creationPlan=${encodeURIComponent(source.creationPlanId)}`;
}
