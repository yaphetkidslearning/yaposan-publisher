const el = (
  id: string,
  name: string,
  type: PublisherElement["type"],
  x: number,
  y: number,
  width: number,
  height: number,
  zIndex: number,
  extra: Partial<PublisherElement> = {},
): PublisherElement => ({
  id,
  name,
  type,
  x,
  y,
  width,
  height,
  rotation: 0,
  zIndex,
  opacity: 1,
  locked: false,
  hidden: false,
  ...extra,
});

const text = (
  id: string,
  value: string,
  x: number,
  y: number,
  width: number,
  height: number,
  size: number,
  color: string,
  weight: PublisherElement["fontWeight"] = "700",
  extra: Partial<PublisherElement> = {},
) => el(id, value.slice(0, 24), "text", x, y, width, height, 30, {
  text: value,
  fontSize: size,
  textColor: color,
  fontWeight: weight,
  lineHeight: size * 1.12,
  fontFamily: "Inter",
  ...extra,
});

const rect = (
  id: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fillColor: string,
  extra: Partial<PublisherElement> = {},
) => el(id, id, "rectangle", x, y, width, height, 10, { fillColor, borderWidth: 0, ...extra });

const circle = (
  id: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fillColor: string,
  extra: Partial<PublisherElement> = {},
) => el(id, id, "ellipse", x, y, width, height, 12, { fillColor, borderWidth: 0, ...extra });

const image = (
  id: string,
  uri: string,
  x: number,
  y: number,
  width: number,
  height: number,
  extra: Partial<PublisherElement> = {},
) => el(id, id, "image", x, y, width, height, 8, { imageUri: uri, imageFit: "cover", ...extra });

const page = (
  id: string,
  name: string,
  width: number,
  height: number,
  orientation: "portrait" | "landscape",
  backgroundColor: string,
  elements: PublisherElement[],
): PublisherPage => ({
  id,
  name,
  width,
  height,
  orientation,
  sizeKey: "custom",
  backgroundColor,
  margin: 32,
  bleed: DEFAULT_BLEED,
  elements,
});

function make(config: {
  id: string;
  name: string;
  category: ProfessionalTemplateCategory;
  subcategory: string;
  industry: string;
  style: NonNullable<ProfessionalTemplate["metadata"]["style"]>;
  pageSize: string;
  orientation: TemplateOrientation;
  previewColor: string;
  palette: string[];
  fonts: string[];
  description: string;
  pages: PublisherPage[];
  access?: "free" | "premium" | "team";
}): ProfessionalTemplate {
  return {
    metadata: {
      id: config.id,
      name: config.name,
      category: config.category,
      subcategory: config.subcategory,
      industry: config.industry,
      description: config.description,
      tags: [config.category.toLowerCase(), config.subcategory.toLowerCase(), config.industry.toLowerCase(), "editable", "professional", "method"],
      pageSize: config.pageSize,
      orientation: config.orientation,
      previewColor: config.previewColor,
      palette: config.palette,
      fonts: config.fonts,
      author: "Yaposan Design Studio",
      version: "43.4.6",
      editable: true,
      featured: true,
      trending: true,
      access: config.access ?? "premium",
      createdAt: NOW,
      updatedAt: NOW,
      style: config.style,
      masterTemplateId: config.id,
      qualityScore: 100,
    },
    pages: config.pages,
  };
}

