import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
const root=process.cwd();
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const out=path.join(root,`Yaposan-${pkg.version}-source.zip`);
const excludes=['node_modules','dist','.git','.expo','.env','.env.production','coverage',path.basename(out)];
const args=['-r','-q',out,'.'];
for(const item of excludes) args.push('-x',`${item}/*`,item);
const r=spawnSync('zip',args,{cwd:root,stdio:'inherit'});
if(r.error) throw r.error;
if(r.status!==0) process.exit(r.status??1);
console.log(`Created ${out}`);
