const fs = require('fs');
const p = 'src/templates/phase4371ProfessionalBusinessCards.ts';
const s = fs.readFileSync(p, 'utf8');
const ids = [...s.matchAll(/id:\s*"([^"]+)"/g)].map(m=>m[1]).filter(x=>!x.includes('${'));
const names = [...s.matchAll(/name:\s*"([^"]+Business Card)"/g)].map(m=>m[1]);
const layouts = [...s.matchAll(/layout:(\d+)/g)].map(m=>Number(m[1]));
const errors=[];
if (names.length !== 20) errors.push(`Expected 20 names, found ${names.length}`);
if (new Set(names).size !== names.length) errors.push('Duplicate names found');
if (layouts.length !== 20 || new Set(layouts).size !== 20) errors.push('Layouts must be 1-20 and unique');
if (!s.includes('pages: [')) errors.push('Missing page definitions');
if (!s.includes('"Front"') || !s.includes('"Back"')) errors.push('Missing front/back pages');
if (!s.includes('PublisherElement') || !s.includes('PublisherPage')) errors.push('Missing Publisher types');
const result={templateCount:names.length,uniqueNames:new Set(names).size,uniqueLayouts:new Set(layouts).size,frontAndBack:true,errors};
console.log(JSON.stringify(result,null,2));
if(errors.length) process.exit(1);
